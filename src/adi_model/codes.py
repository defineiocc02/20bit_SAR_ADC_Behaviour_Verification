"""码域位宽的唯一真源。"""

from __future__ import annotations

# 一级（SADC）量化 9 bit，与 ISSCC2024 论文「resulting in 9b quantization in the
# first stage」一致；也是 residual 计算里 coarse 的取值上界。
COARSE_BITS = 9
COARSE_CODES = 1 << COARSE_BITS

# 最终输出 20 bit。
OUTPUT_BITS = 20
OUTPUT_CODES = 1 << OUTPUT_BITS
