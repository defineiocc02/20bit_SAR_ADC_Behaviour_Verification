"""Independent scoreboard: compares RTL dumps against the reference models.

Rules this file follows (task book §6/§12):

* it never invokes the DUT module and never re-implements it;
* it never edits a dump — a mismatch is reported, not repaired;
* a failure report always names sample index, field, expected and actual, and
  the vector-set seed, so the case can be regenerated by hand.

Every comparator returns ``(passed, total, first_mismatch_or_None)``.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VECTORS = ROOT / "verification" / "vectors" / "generated"


@dataclass
class Mismatch:
    """One failing vector field, with everything needed to reproduce it."""

    index: int
    field: str
    expected: int | str
    actual: int | str
    detail: str = ""

    def render(self, module: str, seed: int) -> str:
        """Format the failure block a reviewer can paste into a bug report."""
        return (
            f"First mismatch\n"
            f"  module        : {module}\n"
            f"  vector index  : {self.index}\n"
            f"  field         : {self.field}\n"
            f"  python expect : {self.expected}\n"
            f"  rtl actual    : {self.actual}\n"
            f"  detail        : {self.detail}\n"
            f"  random seed   : {seed}\n"
            f"  regenerate    : python -m verification.vectors.generate --seed {seed}\n"
        )


def field_bits(module: str, field: str) -> int | None:
    """Declared bit width of a generated field, from the vector set's meta.json."""
    meta = VECTORS / module / "meta.json"
    if not meta.is_file():
        return None
    widths = json.loads(meta.read_text()).get("field_width_bits", {})
    return widths.get(field)


def load_mem(path: Path, *, signed: bool = False, bits: int | None = None) -> list[int]:
    """Read a $readmemh dump back into Python ints.

    ``bits`` must be the *declared* field width, not the hex digit count: a
    63-bit field is written as 16 nibbles, so trusting the text width would
    interpret every negative value as a large positive one.
    """
    values: list[int] = []
    digit_bits = 0
    for line in path.read_text(encoding="ascii").splitlines():
        token = line.strip()
        if not token:
            continue
        digit_bits = max(digit_bits, len(token) * 4)
        values.append(int(token, 16))
    width = bits if bits is not None else digit_bits
    values = [v & ((1 << width) - 1) for v in values]
    if signed:
        half = 1 << (width - 1)
        values = [v - (1 << width) if v >= half else v for v in values]
    return values


def load_out(text: str) -> list[list[str]]:
    """Split a DUT dump into per-vector token lists."""
    rows = []
    for line in text.splitlines():
        line = line.strip()
        if line:
            rows.append(line.split())
    return rows


def _seed_of(module: str) -> int:
    meta = VECTORS / module / "meta.json"
    if meta.is_file():
        return int(json.loads(meta.read_text())["seed"])
    return 0


def _require_rows(rows: list[list[str]], expected: int, module: str,
                  field: str = "count") -> Mismatch | None:
    """Reject a dump whose row count does not match the vector count.

    Without this a comparator that only zips rows can silently accept a dump
    that lost its last line: zip stops at the shorter side and every comparison
    passes. Deletion of a trailing row must fail, not shrink the comparison.
    """
    if len(rows) != expected:
        return Mismatch(min(len(rows), expected), field, expected, len(rows),
                        f"{module}: dump has {len(rows)} rows, vectors have {expected}")
    return None


def compare_sadc(out_text: str) -> tuple[int, int, Mismatch | None]:
    """Compare the population count for every comparator pattern."""
    from verification.reference.datapath_ref import sadc_code

    raw = load_mem(VECTORS / "sadc_enc" / "cmp_raw.mem")
    rows = load_out(out_text)
    if len(rows) != len(raw):
        return 0, len(raw), Mismatch(0, "count", len(raw), len(rows), "vector count mismatch")
    for index, (value, row) in enumerate(zip(raw, rows, strict=True)):
        expected = sadc_code(value, n_cmp=511, bits=9)
        actual = int(row[0], 16)
        if expected != actual:
            return index, len(raw), Mismatch(index, "sadc_code", expected, actual)
    return len(raw), len(raw), None


def compare_unit_therm(out_text: str) -> tuple[int, int, Mismatch | None]:
    """Compare the full main/sub mask for every rank/count vector."""
    from verification.reference.datapath_ref import thermometer

    base = VECTORS / "unit_therm"
    main_logical = load_mem(base / "main_logical.mem")
    sub_logical = load_mem(base / "sub_logical.mem")
    main_count = load_mem(base / "main_count.mem")
    sub_count = load_mem(base / "sub_count.mem")
    n_main, n_sub = 63, 8
    rows = load_out(out_text)
    bad = _require_rows(rows, len(main_count), "unit_therm")
    if bad is not None:
        return 0, len(main_count), bad
    for index, row in enumerate(rows):
        main_ranks = [(main_logical[index] >> (6 * p)) & 0x3F for p in range(n_main)]
        sub_ranks = [(sub_logical[index] >> (3 * p)) & 0x07 for p in range(n_sub)]
        expected_main = thermometer(main_ranks, main_count[index])
        expected_sub = thermometer(sub_ranks, sub_count[index])
        actual_main = int(row[0], 16)
        actual_sub = int(row[1], 16)
        # 掩码是 [active_slot, unit] 打包的，必须逐片比，不能只看 slot 0。
        # 只比最低一片时，任何"其余片全错"的 RTL 都能通过。
        for lane in range(8):
            for p, bit in enumerate(expected_main):
                got = (actual_main >> (lane * n_main + p)) & 1
                if got != bit:
                    return index, len(rows), Mismatch(
                        index, f"main_on[slot={lane}][unit={p}]", bit, got)
            for p, bit in enumerate(expected_sub):
                got = (actual_sub >> (lane * n_sub + p)) & 1
                if got != bit:
                    return index, len(rows), Mismatch(
                        index, f"sub_on[slot={lane}][unit={p}]", bit, got)
    return len(rows), len(rows), None


def _signed_from_hex(token: str, bits: int) -> int:
    value = int(token, 16)
    return value - (1 << bits) if value >= (1 << (bits - 1)) else value


def compare_adc2(out_text: str) -> tuple[int, int, Mismatch | None]:
    """Compare bin centre and saturation flag over all ADC2 codes."""
    from verification.reference.datapath_ref import adc2_bin_center

    base = VECTORS / "adc2_dec"
    codes = load_mem(base / "adc2_code.mem", bits=field_bits("adc2_dec", "adc2_code"))
    mins = load_mem(base / "adc2_min_q.mem", signed=True, bits=64)
    maxs = load_mem(base / "adc2_max_q.mem", signed=True, bits=64)
    rows = load_out(out_text)
    bad = _require_rows(rows, len(codes), "adc2_dec")
    if bad is not None:
        return 0, len(codes), bad
    for index, row in enumerate(rows):
        expected, expected_ovf = adc2_bin_center(codes[index], mins[index], maxs[index], 12)
        actual = _signed_from_hex(row[0], 64)
        actual_ovf = int(row[1])
        if expected != actual:
            return index, len(rows), Mismatch(
                index, "fine_q", expected, actual,
                f"code={codes[index]} min={mins[index]} max={maxs[index]}",
            )
        if int(expected_ovf) != actual_ovf:
            return index, len(rows), Mismatch(index, "ovf", int(expected_ovf), actual_ovf)
    return len(rows), len(rows), None


def compare_div_floor(out_text: str, expected_cycles: int = 9) -> tuple[int, int, Mismatch | None]:
    """Compare quotient, error flag and measured latency."""
    from verification.reference.fixed_point import floor_div

    base = VECTORS / "div_floor"
    a_values = load_mem(base / "a.mem", signed=True, bits=field_bits("div_floor", "a"))
    d_values = load_mem(base / "d.mem", bits=field_bits("div_floor", "d"))
    rows = load_out(out_text)
    bad = _require_rows(rows, len(a_values), "div_floor")
    if bad is not None:
        return 0, len(a_values), bad
    for index, row in enumerate(rows):
        a, d = a_values[index], d_values[index]
        if d == 0:
            expected_q, expected_err = 0, 1
        else:
            expected_q, expected_err = floor_div(a, d), 0
        actual_q = _signed_from_hex(row[0], 63)
        actual_err = int(row[1])
        cycles = int(row[2])
        if expected_q != actual_q:
            return index, len(rows), Mismatch(
                index, "q", expected_q, actual_q, f"a={a} d={d}"
            )
        if expected_err != actual_err:
            return index, len(rows), Mismatch(index, "err", expected_err, actual_err)
        if cycles != expected_cycles:
            return index, len(rows), Mismatch(
                index, "latency_cycles", expected_cycles, cycles,
                "timing.yaml :: div_floor.latency_cycles",
            )
    return len(rows), len(rows), None


def compare_rdac_drv(out_text: str) -> tuple[int, int, Mismatch | None]:
    """Reference semantics: clear-then-scatter, last duplicate wins, out-of-range ignored."""
    base = VECTORS / "rdac_drv"
    ids = load_mem(base / "slice_id.mem")
    main_on = load_mem(base / "main_on.mem")
    sub_on = load_mem(base / "sub_on.mem")
    load = load_mem(base / "load.mem")
    rst_n = load_mem(base / "rst_n.mem")
    rows = load_out(out_text)
    bad = _require_rows(rows, len(ids), "rdac_drv")
    if bad is not None:
        return 0, len(ids), bad

    n_slices, n_active, n_main, n_sub = 18, 8, 63, 8
    state_sel = 0
    state_main = [0] * n_slices
    state_sub = [0] * n_slices
    for index, row in enumerate(rows):
        if rst_n[index] == 0:
            state_sel = 0
            state_main = [0] * n_slices
            state_sub = [0] * n_slices
        elif load[index] == 1:
            state_sel = 0
            state_main = [0] * n_slices
            state_sub = [0] * n_slices
            for lane in range(n_active):
                sid = (ids[index] >> (5 * lane)) & 0x1F
                if sid >= n_slices:
                    continue
                state_sel |= 1 << sid
                state_main[sid] = (main_on[index] >> (lane * n_main)) & ((1 << n_main) - 1)
                state_sub[sid] = (sub_on[index] >> (lane * n_sub)) & ((1 << n_sub) - 1)
        actual_sel = int(row[0], 16)
        if state_sel != actual_sel:
            return index, len(rows), Mismatch(index, "slice_sel", state_sel, actual_sel)
        # Compare the active rows only; the dump packs 18 rows of 63 bits.
        for sid in range(n_slices):
            actual_row = (int(row[1], 16) >> (sid * n_main)) & ((1 << n_main) - 1)
            if state_main[sid] != actual_row:
                return index, len(rows), Mismatch(
                    index, f"main_sw[{sid}]", state_main[sid], actual_row
                )
            actual_sub_row = (int(row[2], 16) >> (sid * n_sub)) & ((1 << n_sub) - 1)
            if state_sub[sid] != actual_sub_row:
                return index, len(rows), Mismatch(
                    index, f"sub_sw[{sid}]", state_sub[sid], actual_sub_row
                )
    return len(rows), len(rows), None


def compare_recon_core(out_text: str, expected_latency: int = 11) -> tuple[int, int, Mismatch | None]:
    """Bit-exact check of the full reconstruction, including status bits.

    The weight ROM is regenerated from the vector seed rather than read from a
    second copy, so the bench and the reference cannot drift apart silently.
    """
    from verification.reference.datapath_ref import (
        adc2_bin_center,
        recon_terms,
        reconstruct,
    )
    from verification.vectors.generate import gen_recon_core

    seed = _seed_of("recon_core")
    rom = gen_recon_core(seed).extra["w_rom"]  # type: ignore[attr-defined]
    base = VECTORS / "recon_core"
    ids = load_mem(base / "slice_id.mem", bits=40)
    mains = load_mem(base / "main_on.mem", bits=504)
    subs = load_mem(base / "sub_on.mem", bits=64)
    codes = load_mem(base / "adc2_code.mem", bits=12)
    injs = load_mem(base / "inj_q.mem", signed=True, bits=64)
    offs = load_mem(base / "offset_q.mem", signed=True, bits=64)
    mins = load_mem(base / "adc2_min_q.mem", signed=True, bits=64)
    maxs = load_mem(base / "adc2_max_q.mem", signed=True, bits=64)
    sample_ids = load_mem(base / "sample_id.mem", bits=32)
    rows = load_out(out_text)
    bad = _require_rows(rows, len(ids), "recon_core")
    if bad is not None:
        return 0, len(ids), bad

    n_main, n_sub = 63, 8
    for index, row in enumerate(rows):
        weights: list[int] = []
        on: list[int] = []
        sign: list[int] = []
        for lane in range(8):
            sid = (ids[index] >> (5 * lane)) & 0x1F
            if sid >= rom.shape[0]:
                raise IndexError(f"vector {index} names slice {sid} outside the ROM")
            for unit in range(n_main + n_sub):
                selected = (
                    (mains[index] >> (lane * n_main + unit)) & 1
                    if unit < n_main
                    else (subs[index] >> (lane * n_sub + (unit - n_main))) & 1
                )
                weights.append(int(rom[sid][unit]))
                on.append(selected)
                sign.append(1 - 2 * selected)
        # Contract §3.2: ordinary units carry a = 1 regardless of the switch
        # state, so gain = sum(W) here. `on` only moves rails.
        terms = recon_terms(weights, on, sign)
        fine, _ = adc2_bin_center(codes[index], mins[index], maxs[index], 12)
        result = reconstruct(
            fine_q=fine, offset_q=offs[index], injection_q=injs[index], terms=terms
        )
        actual_word = int(row[0], 16)
        if result.word != actual_word:
            return index, len(rows), Mismatch(
                index, "dout", result.word, actual_word,
                f"gain={terms.gain_q30} rails={terms.rails_q30} total={terms.total_q30}",
            )
        # gain<=0 是结构性错误，不是溢出；adc2 bin-centre 饱和要单独上报。
        # 这两个 flag 之前完全没比，等于 RTL 可以永久拉高它们而仍判通过。
        expected_gain_err = 1 if terms.gain_q30 <= 0 else 0
        _, expected_adc2_ovf = adc2_bin_center(codes[index], mins[index], maxs[index], 12)
        for name, expected, column in (
            ("clip_low", int(result.clip_low), 1),
            ("clip_high", int(result.clip_high), 2),
            ("acc_ovf", int(result.acc_ovf), 3),
            ("gain_err", expected_gain_err, 4),
            ("adc2_ovf", int(expected_adc2_ovf), 5),
            ("result_sample_id", int(sample_ids[index]), 6),
        ):
            actual = int(row[column])
            if expected != actual:
                return index, len(rows), Mismatch(index, name, expected, actual)
        latency = int(row[7])
        if latency != expected_latency:
            return index, len(rows), Mismatch(
                index, "latency_cycles", expected_latency, latency,
                "timing.yaml :: recon_core.latency_cycles",
            )
    return len(rows), len(rows), None


def compare_slice_pool(out_text: str) -> tuple[int, int, Mismatch | None]:
    """Cycle-accurate scheduler comparison, including sample_id and prime flag."""
    from verification.reference.scheduler_ref import pack_ids, reset_state, step

    seed_value = 1831565813  # POOL_SHUFFLE_SEED, mirrored in rtl_params.vh
    base = VECTORS / "slice_pool_ctrl"
    advance = load_mem(base / "advance.mem")
    enable = load_mem(base / "enable.mem")
    shuffle = load_mem(base / "shuffle.mem")
    rst_n = load_mem(base / "rst_n.mem")
    rows = load_out(out_text)
    bad = _require_rows(rows, len(advance), "slice_pool_ctrl")
    if bad is not None:
        return 0, len(advance), bad

    state = reset_state(seed_value)
    # The bench holds the design in its reset value for the first edges while it
    # settles; replay from reset so both sides start from the same definition.
    for index, row in enumerate(rows):
        state = step(state, rst_n=rst_n[index], enable=enable[index],
                     advance=advance[index], shuffle=shuffle[index], seed=seed_value)
        expected = {
            "acquiring_ids": pack_ids(state.acquiring_ids),
            "converting_ids": pack_ids(state.converting_ids),
            "acquiring_mask": state.acquiring_mask,
            "converting_mask": state.converting_mask,
            "conversion_valid": state.conversion_valid,
            "sample_id": state.sample_id,
            "acquisition_primed": state.primed,
        }
        for column, (name, want) in enumerate(expected.items()):
            actual = int(row[column], 16) if name.endswith(("ids", "mask")) else int(row[column])
            if want != actual:
                return index, len(rows), Mismatch(
                    index, name, want, actual,
                    f"edge {index} rst_n={rst_n[index]} en={enable[index]} "
                    f"adv={advance[index]} shuffle={shuffle[index]}",
                )
        if int(row[7]) != index + 1:
            return index, len(rows), Mismatch(index, "cycle", index + 1, int(row[7]))
    return len(rows), len(rows), None
