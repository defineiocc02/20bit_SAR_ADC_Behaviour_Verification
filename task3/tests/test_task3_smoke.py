"""task3 模型层的导入冒烟。"""

from __future__ import annotations


def test_caaz20_public_names_are_importable() -> None:
    """CAAZ 参考模型能被导入，且公开入口没有被改名。"""
    from task3.model import caaz20

    for name in ("Input", "Output", "CaazOracle"):
        assert hasattr(caaz20, name), f"task3.model.caaz20 缺少公开名 {name}"
