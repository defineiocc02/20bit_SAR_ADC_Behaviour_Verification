# 本导出器自己的激励波形选择（常数而非魔数，便于从外部复算）。
# 与 tools/export_rtl_params.py 的同名常量是各自独立的**选择**，不要求相等。
GOLDEN_TONE_NUM = 73
GOLDEN_TONE_DEN = 2048
GOLDEN_AMPLITUDE_FRAC = 0.8

M1_SAMPLES = 1024
M5_SIDS = (0, 1, 7, 8, 63, 64, 255, 511)
# 注意口径：code c 对应的主/子单位数是 (c // n_sub, c % n_sub)，不是 c 本身。
M5_MAIN_COUNTS = (0, 1, 2, 31, 32, 62, 63)
M5_SUB_COUNTS = (0, 1, 4, 7)


def _hex(value: int, digits: int) -> str:
    """Render a non-negative integer as fixed-width hex."""
    if value < 0:
        raise ValueError("_hex takes non-negative values; use _shex for signed fields")
    return f"{value:0{digits}x}"


def _shex(value: int, digits: int) -> str:
    """Render a signed integer as fixed-width two's-complement hex."""
    return f"{value & ((1 << (4 * digits)) - 1):0{digits}x}"


def _json_text(obj: Any) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False, allow_nan=False) + "\n"


def _write(path: pathlib.Path, text: str, *, check: bool, drift: list[str]) -> None:
    if check:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            drift.append(str(path))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


# ----------------------------------------------------------------------
# M1：DEM 状态推进（按 bank 内序号）
# ----------------------------------------------------------------------
def build_m1(cfg: Config) -> tuple[str, dict[str, Any]]:
    """Golden sid sequence for the model's real A/B bank alternation."""
    bank = np.arange(M1_SAMPLES, dtype=np.int64) % 2
    sid = dem_state_sequence(M1_SAMPLES, cfg, bank)
    lines = [
        "// p1_m1_sid.hex  (generated by tools/export_rtl_vectors.py)",
        f"// samples={M1_SAMPLES}  cols: n(4) bank(1) en_a(1) en_b(1) sid_exp(3)",
        "// DRIVE: en_a = (bank==0), en_b = (bank==1); sample sid_a/sid_b in that same cycle.",
        "#DATA",
    ]
    for n in range(M1_SAMPLES):
        en_a = 0 if bank[n] else 1
        en_b = 1 if bank[n] else 0
        lines.append(f"{_hex(n, 4)} {bank[n]} {en_a} {en_b} {_hex(int(sid[n]), 3)}")
    stats = {
        "samples": M1_SAMPLES,
        "distinct_sids": int(np.unique(sid).size),
        "first_sid_by_bank": {
            "0": int(sid[0]),
            "1": int(sid[1]),
        },
        "per_bank_all_states_seen": bool(
            np.unique(sid[bank == 0]).size == 512 and np.unique(sid[bank == 1]).size == 512
        ),
    }
    return "\n".join(lines) + "\n", stats


# ----------------------------------------------------------------------
# M2：物理地址 -> 逻辑位置（order 的逆）
# ----------------------------------------------------------------------
def build_m2(cfg: Config) -> tuple[str, dict[str, Any], dict[str, np.ndarray]]:
    """Exhaustive inverse-permutation golden for all 512 DEM states."""
    n_main, n_sub = int(cfg.dac_n_main), int(cfg.dac_n_sub)
    sids = np.arange(512, dtype=np.int64)
    command = split_switch_command(cfg, np.zeros(512), sids)

    main_logical = np.empty((512, n_main), dtype=np.int64)
    sub_logical = np.empty((512, n_sub), dtype=np.int64)
    for s in range(512):
        row = command.main_order[s]
        main_logical[s, row] = np.arange(n_main)  # j_inv[p] = position of p in main_order
        row_s = command.sub_order[s]
        sub_logical[s, row_s] = np.arange(n_sub)

    lines = [
        "// p1_m2_jinv.hex  (generated by tools/export_rtl_vectors.py)",
        "// cols: sid(3) main_logical[63](2 each) sub_logical[8](2 each)",
        "// main_logical[p] = logical position of physical main address p; MUST be a permutation of 0..62.",
        "#DATA",
    ]
    for s in range(512):
        fields = " ".join(_hex(int(v), 2) for v in main_logical[s])
        subfields = " ".join(_hex(int(v), 2) for v in sub_logical[s])
        lines.append(f"{_hex(s, 3)} {fields} {subfields}")

    ok_main = all(sorted(main_logical[s].tolist()) == list(range(n_main)) for s in range(512))
    ok_sub = all(sorted(sub_logical[s].tolist()) == list(range(n_sub)) for s in range(512))
    if not (ok_main and ok_sub):
        raise AssertionError("order is not a bijection: the DEM invariant would be broken")
    stats = {
        "states": 512,
        "main_addresses": n_main,
        "sub_addresses": n_sub,
        "cases": int(512 * (n_main + n_sub)),
        "bijection_verified": True,
    }
    return (
        "\n".join(lines) + "\n",
        stats,
        {"main_logical": main_logical, "sub_logical": sub_logical},
    )


# ----------------------------------------------------------------------
# M3：命令 -> 每 slice 主/子计数
# ----------------------------------------------------------------------
def _m3_counts(cfg_bridge: Config, codes: np.ndarray, sids: np.ndarray):
    command = split_switch_command(cfg_bridge, codes.astype(float), sids)
    return command.main_counts, command.sub_counts


def build_m3(cfg: Config) -> tuple[str, dict[str, Any]]:
    """Exhaustive (code, bridge, sid_low) golden plus directed clipping cases."""
    n_active = int(cfg.n_active)
    levels = int(cfg.dac_levels)
    plain = replace(cfg, dem_enable=True, dem_bridge_enable=False)
    bridged = replace(cfg, dem_enable=True, dem_bridge_enable=True)

    lines = [
        "// p1_m3.hex  (generated by tools/export_rtl_vectors.py)",
        "// cols: coarse(3) dither(2 signed) bridge(1) sid_low(1) "
        "main_count[8](2 each) sub_count[8](1 each) rdac_over(1)",
        "// exhaustive part: coarse 0..511 x dither=0 x bridge{0,1} x sid_low 0..7",
        "// directed part: coarse in {0,1,255,510,511} x dither in -8..8 (k formation + clipping)",
        "#DATA",
    ]

    exhaustive = 0
    for code in range(levels):
        for bridge in (0, 1):
            cfg_b = bridged if bridge else plain
            sid = np.full(1, 0, dtype=np.int64)
            for sid_low in range(n_active):
                sid[0] = sid_low
                mc, sc = _m3_counts(cfg_b, np.array([code]), sid)
                lines.append(
                    f"{_hex(code, 3)} {_shex(0, 2)} {bridge} {sid_low} "
                    + " ".join(_hex(int(v), 2) for v in mc[0])
                    + " "
                    + " ".join(_hex(int(v), 1) for v in sc[0])
                    + " 0"
                )
                exhaustive += 1

    directed = 0
    for code in (0, 1, 255, 510, 511):
        for dither in range(-8, 9):
            k = code + dither
            clipped = min(max(k, 0), levels - 1)
            over = int(k < 0 or k > levels - 1)
            mc, sc = _m3_counts(plain, np.array([clipped]), np.zeros(1, np.int64))
            lines.append(
                f"{_hex(code, 3)} {_shex(dither, 2)} 0 0 "
                + " ".join(_hex(int(v), 2) for v in mc[0])
                + " "
                + " ".join(_hex(int(v), 1) for v in sc[0])
                + f" {over}"
            )
            directed += 1

    stats = {"exhaustive_cases": exhaustive, "directed_cases": directed, "levels": levels}
    return "\n".join(lines) + "\n", stats


# ----------------------------------------------------------------------
# M5：温度计掩码
# ----------------------------------------------------------------------
def _m5_golden(cfg: Config, sids: np.ndarray, codes: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Return the model's own (main_on, sub_on) masks of shape (N, n_active, n_units).

    ``_terms`` does not return the ON mask directly: it folds it into
    ``b_minus_dac = injection - v_fs*(2*plus - 1)`` and leaves ``signal`` at all
    ones. With the injection set to zero that affine map is exactly invertible, so
    the mask is recovered as ``(1 - b_minus_dac/v_fs) / 2``. The result is asserted
    binary, which is what makes this an extraction rather than a guess: if
    ``_terms`` ever changes that encoding, this raises instead of silently
    producing a wrong golden.

    只有 **sampling** 模式会在 `b_minus_dac` 上再叠加一层（掩码单位被改写成轨电压），
    其余模式（off / analog / quantizer）这个仿射关系都是精确可逆的 —— 早先这里写成
    "只允许 off"，过严，把 quantizer 的链路向量挡在了门外。
    """
    if cfg.dither_mode == "sampling":
        raise ValueError("M5 golden extraction is invalid for dither_mode='sampling'")
    spec = CalibrationSpec.from_config(cfg)
    n = len(sids)
    data = DigitalObservation(
        spec,
        np.tile(np.arange(spec.n_active, dtype=np.int64), (n, 1)),
        np.asarray(codes, dtype=float),
        np.asarray(sids, dtype=np.int64),
        np.zeros(n, dtype=np.int64),
        np.zeros(n),
        np.zeros(n),
        np.zeros(n, bool),
        True,
    )
    _, _, b_minus_dac = _terms(data, 0, n)
    plus = (1.0 - b_minus_dac / spec.v_fs) / 2.0
    if not np.all((plus == 0.0) | (plus == 1.0)):
        raise AssertionError("extracted ON mask is not binary; _terms changed its encoding")
    main_on = plus[:, :, : spec.dac_n_main].astype(np.int64)
    sub_on = plus[:, :, spec.dac_n_main :].astype(np.int64)
    return main_on, sub_on


def _pack_bits(bits: np.ndarray) -> int:
    """Pack a 0/1 vector into an integer, **LSB = physical address 0**.

    LSB-first on purpose: the RTL port is ``logic [N-1:0] main_on`` where index p
    is address p, so the testbench can compare the packed field with
    ``{1'b0, main_on[a]}`` directly. MSB-first packing would force the TB to
    reverse the field, which is exactly the kind of silent index error the
    contract's §6 A8 warns about.
    """
    value = 0
    for index, bit in enumerate(bits):
        if int(bit):
            value |= 1 << index
    return value


def build_m5(cfg: Config) -> tuple[str, dict[str, Any]]:
    """Direct bit-exact mask golden on a sid x (main_count, sub_count) grid.

    The grid is stated in **unit counts**, not codes: a code ``c`` maps to
    ``(main_count, sub_count) = (c // n_sub, c % n_sub)``, which is what the
    thermometer actually receives. Codes are rebuilt from the grid so that the
    golden still comes from the model's own ``_terms``.
    """
    n_active, n_sub = int(cfg.n_active), int(cfg.dac_n_sub)
    # 桥接零和交换**故意**让各 slice 的计数不同（那正是它的 DEM 作用），
    # 所以这个"均匀计数"网格必须把桥接关掉。桥接本身在 M3 的穷举里单独覆盖；
    # M5 对**非均匀** count 向量的行为由 TB 的稠密扫描（用 p1_m2_jinv.hex 当黄金）覆盖。
    uniform = replace(cfg, dem_bridge_enable=False)
    # 两个来源合起来：全部 512 个 sid 走边界计数（保证每个 sid 的映射都过一遍 M5），
    # 外加 8 个 sid 的中间计数（保证计数维度也稠密）。
    cases = [(s, 0, 0) for s in range(512)]
    cases += [(s, cfg.dac_n_main, 0) for s in range(512)]
    cases += [(s, mc, sc) for s in M5_SIDS for mc in M5_MAIN_COUNTS for sc in M5_SUB_COUNTS]
    sids = np.array([s for s, _, _ in cases], dtype=np.int64)
    codes = np.array([mc * n_sub + sc for _, mc, sc in cases], dtype=np.int64)
    main_on, sub_on = _m5_golden(uniform, sids, codes)

    lines = [
        "// p1_m5_masks.hex  (generated by tools/export_rtl_vectors.py)",
        "// cols: sid(3) main_count(2) sub_count(1) main_on[8](16 each) sub_on[8](2 each)",
        "// packed fields are LSB-first: bit p = physical main address p, bit q = sub address q.",
        "// dense sweep (512 sid x main_count 0..70) is recomputed in the TB from p1_m2_jinv.hex.",
        "#DATA",
    ]
    for i, (s, mc, sc) in enumerate(cases):
        main_fields = " ".join(_hex(_pack_bits(main_on[i, a]), 16) for a in range(n_active))
        sub_fields = " ".join(_hex(_pack_bits(sub_on[i, a]), 2) for a in range(n_active))
        lines.append(f"{_hex(s, 3)} {_hex(mc, 2)} {_hex(sc, 1)} {main_fields} {sub_fields}")

    # Structural self-check on the golden itself: the mask must be a pure thermometer.
    for i, (s, mc, sc) in enumerate(cases):
        for a in range(n_active):
            if int(main_on[i, a].sum()) != mc:
                raise AssertionError(
                    f"golden main mask for sid={s} main_count={mc} is not a thermometer"
                )
            if int(sub_on[i, a].sum()) != sc:
                raise AssertionError(
                    f"golden sub mask for sid={s} sub_count={sc} is not a thermometer"
                )
    stats = {
        "cases": len(cases),
        "all_sids_boundary_cases": 1024,
        "sids": list(M5_SIDS),
        "main_counts": list(M5_MAIN_COUNTS),
        "sub_counts": list(M5_SUB_COUNTS),
        "uniform_counts_require_bridge_off": True,
        "thermometer_structure_verified": True,
    }
    return "\n".join(lines) + "\n", stats


# ----------------------------------------------------------------------
# 链路向量：M1 -> M2 -> M3 -> M5 真实连通
# ----------------------------------------------------------------------
def build_chain(cfg: Config, n_samples: int = 256) -> tuple[str, dict[str, Any]]:
    """Stimulus + expected masks for the **connected** M1→M2→M3→M5 chain.

    Why this file exists: T1/T4/T5 各自把 DUT 的输入直接喂进去，`m2_sid` 是 TB 写死的
    常量。于是"M1 的 sid 有没有正确接到 M2"这件事**从未被验证过** —— 独立复核
    （2026-09-18）指出这是 P1 与后续阶段的接缝。本文件让 TB 只提供
    (bank, coarse, dither, bridge)，其余全部由 RTL 自己串起来：
    M1 出 sid -> M2 出逻辑位置 -> M3（sid_low 取自 M1）出计数 -> M5 出掩码。

    期望掩码由模型自己的 `_terms` 给出（见 `_m5_golden` 的提取说明）。

    Note:
        用 `dither_mode="quantizer"`：该模式下 dither 非零（让 M3 的 dither 支路也进链路），
        而 `_terms` 的采样 dither 分支**不会**被触发，故掩码提取仍然精确。
        `dem_enable=True` 是硬要求 —— 见 §0.2 的陷阱说明。

    Args:
        cfg: 已解析的配置；内部会施加本测试所需的覆盖项。
        n_samples: 采样数。

    Returns:
        ``(text, stats)``。
    """
    from adi_model.pipeline import run_pipeline
    from adi_model.sampler import sine_input

    run_cfg = replace(cfg, dem_enable=True, dither_mode="quantizer", dither_discrete=True)
    result = run_pipeline(
        run_cfg,
        sine_input(GOLDEN_AMPLITUDE_FRAC * cfg.v_fs, cfg.fs * GOLDEN_TONE_NUM / GOLDEN_TONE_DEN),
        n_samples,
    )
    units = int(cfg.dac_levels) // (2 ** int(cfg.b1))
    coarse = np.asarray(result.coarse[:n_samples], dtype=np.int64)
    k = np.asarray(np.rint(result.k[:n_samples]), dtype=np.int64)
    dither = k - coarse * units
    bank = np.asarray(result.bank[:n_samples], dtype=np.int64)
    sid = np.asarray(result.sid[:n_samples], dtype=np.int64)
    bridge = int(bool(cfg.dem_bridge_enable))

    # 掩码金标必须按**模型给的 sid**算，而不是按 RTL 的 sid —— 这样链路一旦错位就会红。
    uniform = replace(run_cfg, dem_bridge_enable=bool(bridge))
    codes = coarse * units + dither
    main_on, sub_on = _m5_golden(uniform, sid, codes)

    lines = [
        "// p1_chain.hex  (generated by tools/export_rtl_vectors.py)",
        "// cols: bank(1) coarse(3) dither(2 signed) bridge(1) "
        "main_on[8](16 each) sub_on[8](2 each)",
        "// 本文件**只给激励与期望掩码**，不给 main_count/sub_count：",
        "// 计数必须由 RTL 的 M3 自己算出来，否则这条链路测的就不是连通性。",
        "// sid_low 同理取自 RTL 的 M1 输出，不从文件读。",
        "#DATA",
    ]
    n_act = int(cfg.n_active)
    for i in range(n_samples):
        fields = " ".join(_hex(_pack_bits(main_on[i, a]), 16) for a in range(n_act))
        subf = " ".join(_hex(_pack_bits(sub_on[i, a]), 2) for a in range(n_act))
        lines.append(
            f"{bank[i] & 1} {_hex(int(coarse[i]), 3)} {_shex(int(dither[i]), 2)} {bridge} "
            + fields
            + " "
            + subf
        )

    stats = {
        "samples": n_samples,
        "dither_mode": "quantizer",
        "bridge": bridge,
        "nonzero_dither_samples": int(np.count_nonzero(dither != 0)),
        "distinct_sids": int(np.unique(sid[:n_samples]).size),
        "covers_m3_sid_low": True,
        "note": "T7 只驱动 bank/coarse/dither/bridge；sid/sid_low/count 全部由 RTL 产生",
    }
    return "\n".join(lines) + "\n", stats


# ----------------------------------------------------------------------
# P2：L0（div_floor / adc2_dec）、L2（oracle / 饱和 / 真实掩码 / 斜坡）、L3（链路）
# ----------------------------------------------------------------------
# 本导出器自己的 P2 规模与波形选择（常数而非魔数，便于外部复算）。
# 与 tools/export_rtl_params.py 的同名常量是各自独立的**选择**，不要求相等。
P2_TONE_NUM = 1
P2_TONE_DEN = 4096
P2_AMPLITUDE_FRAC = 1.0
# L3 链路的 coarse 必须覆盖 [0, 511] **全域**，否则"coarse ≈ 0 附近"没有对照值，
# 窄化实验在那里看到的 clip_high 只能登记、不能下结论。实测：A = 1.0*v_fs、f = fs/4096、
# 相位 0.5、4096 点是**唯一**一组一次跑满 512 个 coarse 的便宜配置（相位 0 会缺 125，
# 相位 1.5 缺 432，2/4096 缺 98/326，1/8192 跑 8192 点才满）。
# 这里刻意把边界情形一起收进来（会有 clip 与 rdac_over 行），因为它们正是要对照的那一段。
P2_LINK_PHASE = 0.5
P2_MASKS_TONE_NUM = 137
P2_MASKS_TONE_DEN = 4096
P2_MASKS_AMPLITUDE_FRAC = 0.62
P2_MASKS_SAMPLES = 512
P2_LINK_SAMPLES = 4096
