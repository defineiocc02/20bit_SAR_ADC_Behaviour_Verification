def _p2_observation(spec, adc2_code, *, slice_ids=None, rdac_code=None, injection=None):
    """Assemble the minimal legal observation a golden computation needs."""
    n = len(adc2_code)
    return DigitalObservation(
        spec,
        np.zeros((n, spec.n_active), np.int64)
        if slice_ids is None
        else np.asarray(slice_ids, np.int64),
        np.zeros(n) if rdac_code is None else np.asarray(rdac_code, float),
        np.zeros(n, np.int64),
        np.asarray(adc2_code, np.int64),
        np.zeros(n),
        np.zeros(n) if injection is None else np.asarray(injection, float),
        np.zeros(n, bool),
        True,
    )


def _p2_on_masks(cfg: Config, slice_ids, sids, codes):
    """Recover the model's own unary ON masks by decoding ``_terms``.

    ``_terms`` folds the ON mask into ``b_minus_dac``; with the injection set to
    zero that affine map is exactly invertible. The result is asserted binary,
    so a change of encoding raises instead of silently producing a wrong golden.
    """
    if cfg.dither_mode == "sampling":
        raise ValueError("mask extraction is invalid for dither_mode='sampling'")
    spec = CalibrationSpec.from_config(cfg)
    n = len(codes)
    data = DigitalObservation(
        spec,
        np.asarray(slice_ids, np.int64),
        np.asarray(codes, float),
        np.asarray(sids, np.int64),
        np.zeros(n, np.int64),
        np.zeros(n),
        np.zeros(n),
        np.zeros(n, bool),
        True,
    )
    _, _, b_minus_dac = _terms(data, 0, n)
    plus = (1.0 - b_minus_dac / spec.v_fs) / 2.0
    if not np.all((plus == 0.0) | (plus == 1.0)):
        raise AssertionError("extracted ON mask is not binary; _terms changed its encoding")
    return (
        plus[:, :, : spec.dac_n_main].astype(np.int64),
        plus[:, :, spec.dac_n_main :].astype(np.int64),
    )


def _p2_operand_peaks(model: FixedPointReconstructor, data: DigitalObservation):
    """Measure the six checked operands and cross-check the model's own peak ledger.

    The measurement repeats the operand list of ``FixedPointReconstructor.reconstruct``
    only to obtain **width statistics** (contract §14 D3), never an expected value.
    It is validated against ``CodeStream.peak_accumulator_bits``, which the model
    computes independently; a disagreement raises.
    """
    fmt = model.format
    vscale = 2**fmt.voltage_fraction_bits
    wscale = 2**fmt.weight_fraction_bits
    count = 2**fmt.output_bits
    keys = ("op1", "op2", "op3", "num", "shifted", "denom")
    peaks = dict.fromkeys(keys, 0)
    n = len(data.rdac_code)
    for start in range(0, n, 256):
        stop = min(start + 256, n)
        ids, signal, b_minus_dac = _terms(data, start, stop)
        injection = data.common_injection_v[start:stop]
        signs = np.rint((b_minus_dac - injection[:, None, None]) / model.spec.v_fs)
        weights = model.weights_q[ids]
        rails = np.sum(weights * signs.astype(np.int64), axis=(1, 2))
        gains = np.sum(weights * signal.astype(np.int64), axis=(1, 2))
        totals = np.sum(weights, axis=(1, 2))
        for j in range(stop - start):
            k = start + j
            fine = model.adc2_min_q + round_even_divide(
                (2 * int(data.adc2_code[k]) + 1) * (model.adc2_max_q - model.adc2_min_q),
                2 ** (model.spec.adc2_n_bits + 1),
            )
            inj_q = int(np.rint(injection[j] / model.spec.v_fs * vscale))
            gain = int(gains[j])
            op1 = (fine - model.offset_q) * wscale
            op2 = int(rails[j]) * vscale
            op3 = int(totals[j]) * inj_q
            num = op1 - op2 - op3
            operands = (op1, op2, op3, num, (num + gain * vscale) * count, 2 * gain * vscale)
            for key, value in zip(keys, operands, strict=True):
                bits = abs(value).bit_length()
                if bits > peaks[key]:
                    peaks[key] = bits
    return {key: int(value) for key, value in peaks.items()}, max(1, max(peaks.values()) + 1)


def _p2_require_marker(text: str, name: str) -> None:
    """Refuse to ship a vector whose ``#DATA`` marker or body is malformed."""
    lines = text.splitlines()
    markers = [i for i, line in enumerate(lines) if line == "#DATA"]
    if len(markers) != 1 or not lines[markers[0] + 1]:
        raise AssertionError(f"{name}: #DATA marker or body is malformed")
    if not all(line.startswith("//") for line in lines[: markers[0]]):
        raise AssertionError(f"{name}: comment header contains a non-comment line")


def _p2_check_size(name: str, text: str) -> int:
    """Enforce the pre-commit 512 KB per-file budget and return the byte count."""
    size = len(text.encode("utf-8"))
    if size >= VECTOR_LIMIT_BYTES:
        raise AssertionError(f"{name} is {size} B, over the {VECTOR_LIMIT_BYTES} B budget")
    return size


