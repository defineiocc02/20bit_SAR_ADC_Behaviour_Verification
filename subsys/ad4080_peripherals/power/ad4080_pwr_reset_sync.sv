`timescale 1ns/1ps

// =============================================================================
// 文件名     : ad4080_pwr_reset_sync.sv
// 模块名     : ad4080_pwr_reset_sync
// 版本       : v1.0
// 功能       : 在给定的时钟域建立异步断言、同步释放的低有效复位。
//
// 设计说明   :
//   * 目的时钟停止时仍能进入安全状态。恢复时必须在该时钟域获得两个有效沿。
//   * 输入的电源有效信号应先做硬件电平转换和有效态钳位，由接收方的供电域驱动。
//   * 两级属性仅提供实现意图。复位树、亚稳态 MTBF 和 recovery/removal
//     仍须使用目标库及工具验证。用途包含跨域返回的就绪指示。
//
// 变更记录   : 初始版本，暂无变更记录。
// =============================================================================
module ad4080_pwr_reset_sync (
    // --- 目的时钟与保持条件 ---
    input  logic clk_i,       // 释放所在时钟域；停钟时仍接受异步断言
    input  logic hold_ni,     // 0 强制安全状态；合成后需映射到有效的异步清零
    output logic ready_no    // 低有效复位，在第二个满足条件的目的时钟沿释放
);
    // =========================================================================
    // 1. 复位保持和释放
    // =========================================================================
    (* ASYNC_REG = "TRUE" *) logic [1:0] release_q; // 两个紧邻的同步级

    // [复位] 只有异步拉低可直接穿过同步级。拉高先由第一级吸收近沿变化，
    // 第二级提供可在本域使用的释放信号，避免同域寄存器跨不同拍开始运行。
    always_ff @(posedge clk_i or negedge hold_ni) begin
        if (!hold_ni) begin
            release_q <= 2'b00;
        end else begin
            release_q <= {release_q[0], 1'b1};
        end
    end

    assign ready_no = release_q[1];
endmodule
