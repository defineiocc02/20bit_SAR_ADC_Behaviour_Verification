def _p2_sat_model(scale_bits: int) -> FixedPointReconstructor:
    """Return the oracle-ish model used by the saturation vectors."""
    spec = CalibrationSpec(
        dac_n_main=1,
        dac_n_sub=2,
        n_active=1,
        dac_complete_range=True,
        dem_enable=False,
        dem_bridge_enable=False,
        n_slices=1,
        v_fs=3.0,
        adc2_n_bits=P2_SAT_ADC2_BITS,
        adc2_v_min=0.0,
        adc2_v_max=6.0,
        dither_mode="off",
        dither_split_bank="sub",
        dither_units_range=0,
        dither_discrete=True,
    )
    scale = float(2**scale_bits)
    return FixedPointReconstructor.from_weights(spec, [[0.5 * scale, 0.25 * scale, 0.25 * scale]])


def _p2_sat_probe(model, code: int, inj_q: int) -> tuple[int, int, int]:
    """Return ``(word, clip_low, clip_high)`` for a one-sample probe."""
    spec = model.spec
    data = _p2_observation(
        spec, np.array([code], np.int64), injection=np.array([inj_q * spec.v_fs / 2**32])
    )
    stream = model.reconstruct(data)
    return int(stream.code[0]), int(stream.clipped_low[0]), int(stream.clipped_high[0])


def _p2_sat_threshold(model, code: int, *, want_low: bool, hi_q: int = 2**34) -> int:
    """Bisect the smallest ``|inj_q|`` whose probe clips at the requested end."""
    lo_q = 0
    while lo_q < hi_q:
        mid = (lo_q + hi_q) // 2
        _, low, high = _p2_sat_probe(model, code, mid if want_low else -mid)
        if low if want_low else high:
            hi_q = mid
        else:
            lo_q = mid + 1
    if lo_q >= 2**34:
        raise AssertionError(f"no clipping threshold found for adc2_code={code}")
    return lo_q


def build_p2_sat() -> tuple[str, dict[str, Any]]:
    """Export the saturation golden: clipping flags are not the analog overflow flag."""
    lines = [
        "// p2_sat.hex  (generated by tools/export_rtl_vectors.py)",
        "// cols: inj_q(16) adc2_code(3) w_scale(1) exp_word(5) exp_clip_low(1) exp_clip_high(1)",
        "// 口径复现 tests/unit/test_fixed_point.py::",
        "//   test_output_saturation_is_separate_from_analog_saturation（4 bit oracle 后端）。",
        "// w_scale 是本导出器定义的 1 bit 增益选择：0 = 权重 [0.5,0.25,0.25]（ΣW = 2**30）；",
        f"// 1 = 同一组权重寄存器左移 {P2_SAT_SCALE_BITS} 位（ΣW = 2**{30 + P2_SAT_SCALE_BITS} < 2**60，",
        "// 仍合法；TB 侧等价于 w_q_eff = w_q << 8）。它把 gain/denom 挪到另一个量级，",
        "// 但电压寄存器与 inj_q 都不变，于是入/出仍全部受检、期望仍由模型给出。",
        "// 期望值一律来自 FixedPointReconstructor.reconstruct，没有第二份公式。",
        "// ⚠️ 本文件的列里**没有** acc_ovf：冻结的列表达不了“粘滞溢出 + 保持上一拍值”。",
        "//    TB 必须额外断言这些行 acc_ovf == 0（它们都是算术合法的），",
        "//    溢出路径按 docs/rtl/P2_INTERFACE.md §13 由 TB 自己构造越界激励。",
        "#DATA",
    ]
    rows: list[str] = []
    base_inj = np.zeros(16)
    base_inj[0], base_inj[-1] = 0.4, -0.4
    codes = np.arange(16, dtype=np.int64)
    for scale_bits in (0, P2_SAT_SCALE_BITS):
        model = _p2_sat_model(scale_bits)
        stream = model.reconstruct(_p2_observation(model.spec, codes, injection=base_inj))
        for i in range(16):
            rows.append(
                f"{_shex(int(np.rint(base_inj[i] / 3.0 * 2**32)), 16)} {_hex(int(codes[i]), 3)} "
                f"{scale_bits > 0:d} {_hex(int(stream.code[i]), 5)} "
                f"{int(stream.clipped_low[i])} {int(stream.clipped_high[i])}"
            )
    directed = 0
    reached = 0
    for scale_bits in (0, P2_SAT_SCALE_BITS):
        model = _p2_sat_model(scale_bits)
        for code in (0, 15):
            for want_low, sign in ((True, 1), (False, -1)):
                thr = _p2_sat_threshold(model, code, want_low=want_low)
                for inj_q in (sign * (thr - 1), sign * thr):
                    word, low, high = _p2_sat_probe(model, code, inj_q)
                    rows.append(
                        f"{_shex(inj_q, 16)} {_hex(code, 3)} {scale_bits > 0:d} "
                        f"{_hex(word, 5)} {low} {high}"
                    )
                    directed += 1
                    if inj_q == sign * thr:
                        reached += low if sign > 0 else high
    if len(rows) > 64:
        raise AssertionError(f"p2_sat.hex has {len(rows)} rows, over the frozen 64-row budget")
    if reached != directed // 2:
        raise AssertionError("a directed saturation case failed to reach its clip flag")
    text = "\n".join(lines + rows) + "\n"
    _p2_require_marker(text, "p2_sat.hex")
    _p2_check_size("p2_sat.hex", text)
    stats = {
        "cases": len(rows),
        "oracle_reproduction_cases": 32,
        "directed_boundary_cases": directed,
        "directed_clip_flags_reached": int(reached),
        "w_scale_definition": (
            f"0 = sum(W)=2**30, 1 = weights << {P2_SAT_SCALE_BITS} (sum(W)=2**{30 + P2_SAT_SCALE_BITS})"
        ),
        "acc_ovf_column_present": False,
    }
    return text, stats


