def _decode_hex_token(token: str, signed: bool) -> int:
    """Decode one hex token with the field's own width (``int(..., 16)`` alone can't sign)."""
    value = int(token, 16)
    if signed:
        bits = 4 * len(token)
        if value >= 1 << (bits - 1):
            value -= 1 << bits
    return value


def _p2_data_rows(text: str) -> list[list[str]]:
    """Return the token rows that follow the single ``#DATA`` marker."""
    lines = text.splitlines()
    markers = [i for i, line in enumerate(lines) if line == "#DATA"]
    if len(markers) != 1:
        raise AssertionError("expected exactly one #DATA marker")
    return [line.split() for line in lines[markers[0] + 1 :] if line]


def _p2_coverage_audit(files: dict[str, str]) -> dict[str, Any]:
    """Ledger of ``{min, max, distinct}`` per input column, per vector file.

    Why it exists: "某个量到底量到了哪些值" 原本要逐文件翻；更要紧的是"某一列意外
    退化成常量"（例如 dither 全 0、inj_q 全 0）这类事故，在这里一眼可见。
    """
    audit: dict[str, Any] = {}
    for name, spec in P2_AUDIT_COLUMNS.items():
        text = files.get(name)
        if text is None:
            raise AssertionError(f"coverage_audit 登记了 {name}，但产物里没有它")
        rows = _p2_data_rows(text)
        columns: dict[str, dict[str, int]] = {}
        columns_values: list[list[int]] = [[] for _ in spec]
        for row in rows:
            if len(row) != len(spec):
                raise AssertionError(
                    f"{name}: 一行的 token 数是 {len(row)}，列台账写的是 {len(spec)}"
                )
            for index, (_, signed) in enumerate(spec):
                columns_values[index].append(_decode_hex_token(row[index], signed))
        for (column, _), values in zip(spec, columns_values, strict=True):
            columns[column] = {
                "min": min(values),
                "max": max(values),
                "distinct": len(set(values)),
            }
        audit[name] = {"rows": len(rows), "columns": columns}
    # JSON 寄存器镜像不是表，但同样要能被一眼审计
    regs = json.loads(files["p2_regs.json"])
    flat = [int(w) for row in regs["weights_q"] for w in row]
    audit["p2_regs.json"] = {
        "rows": None,
        "note": "JSON 寄存器镜像（不是表）；weights_q 按 18x71 展平后统计",
        "columns": {
            "weights_q": {"min": min(flat), "max": max(flat), "distinct": len(set(flat))},
            "offset_q": {"min": regs["offset_q"], "max": regs["offset_q"], "distinct": 1},
            "adc2_min_q": {"min": regs["adc2_min_q"], "max": regs["adc2_min_q"], "distinct": 1},
            "adc2_max_q": {"min": regs["adc2_max_q"], "max": regs["adc2_max_q"], "distinct": 1},
        },
    }
    return audit


