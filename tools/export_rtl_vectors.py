# L0 adc2_dec：定向用例（含 ties-to-even 的 8 个样例）
# ----------------------------------------------------------------------
def _p2_scalar_cases() -> list[tuple[int, int, int, int, int]]:
    """Return ``(adc2_code, min_q, max_q, offset_q, n_bits)`` directed cases."""
    cases: list[tuple[int, int, int, int, int]] = []
    # (1) ties-to-even。除数必须是 2：用 P_ADC2_BITS = 1（k = 2）驱动，
    #     并取 delta = 2x，于是 round_even_divide(2x, 4) == round_even_divide(x, 2)。
    #     取 delta = 4x 会退化成整除（余数恒为 0），一个平局都测不到。
    for x in (-7, -5, -3, -1, 1, 3, 5, 7):
        cases.append((0, 1000, 1000 + 2 * x, 0, 1))
    # (2) k = 3 的平局（delta ≡ 4 mod 8），两个奇偶方向都要有。
    for mn, delta in ((0, 4), (0, 12), (-50, -12), (-50, 20)):
        cases.append((0, mn, mn + delta, 0, 2))
        cases.append((1, mn, mn + delta, 0, 2))
    # (3) 系统性小位宽扫描：k = 2..5 × 边界 delta × 两个极端码。
    for n_bits in (1, 2, 3, 4):
        span = 2 ** (n_bits + 1)
        for delta in (1, -1, 2, -2, 3, -3, span, -span, span - 1, -(span - 1)):
            for code in (0, 2**n_bits - 1):
                cases.append((code, 7, 7 + delta, 0, n_bits))
    # (4) 生产量级：真的 adc2_min_q / adc2_max_q（paper_literal 名义几何）。
    for code in (0, 1, 100, 2**19, 2**20 - 2, 2**20 - 1):
        cases.append((code, -53687091, 590558003, 0, 20))
    # (5) 寄存器极端值：|-2**63| 端与 |2**63-1| 端，以及两端互换（负 delta）。
    for n_bits in (1, 4, 20):
        for code in (0, 2**n_bits - 1):
            cases.append((code, -(2**63), 2**63 - 1, 0, n_bits))
            cases.append((code, 2**63 - 1, -(2**63), 0, n_bits))
    # (6) offset_q 非零：adc2_dec 不读它，列仍在，用于钉住"它确实不参与"。
    for offset in (12345, -1, 2**62):
        cases.append((0, -100, 100, offset, 8))
    # (7) 最小量程。
    cases += [(0, 5, 6, 0, 1), (0, 5, 6, 0, 20), (0, -1, 0, 0, 1)]
    # (8) **生产位宽 12 的直接覆盖**。生产配置的 12 bit 路径原本只经
    #     p2_masks/p2_ramp/p2_link 由 recon_core 间接走到；这里补上直接用例：
    #     (a) 冻结要求的 delta = 2**33、min_q = 0 六个码；
    #     (b) 真实的生产寄存器三元组（与 p2_recon_coef.hex 同一组值）。
    #     两者都仍由模型的 round_even_divide 出期望，没有第二份公式。
    for code in (0, 1, 2047, 2048, 4094, 4095):
        cases.append((code, 0, 2**33, 0, 12))
    for code in (0, 2047, 4095):
        cases.append((code, -53687091, 590558003, 0, 12))
    return cases


def build_p2_scalar() -> tuple[str, dict[str, Any]]:
    """Export the directed ``adc2_dec`` golden (ties-to-even included)."""
    cases = _p2_scalar_cases()
    lines = [
        "// p2_scalar.hex  (generated by tools/export_rtl_vectors.py)",
        "// cols: adc2_code(3) adc2_n_bits(2) adc2_min_q(16) adc2_max_q(16) offset_q(16) "
        "exp_fine_q(16) exp_ovf(1)",
        "// exp_fine_q = adc2_min_q + round_even_divide((2*c+1)*(max-min), 2**(n_bits+1))，",
        "// 直接取自 Python 模型 adi_model.fixed_point.round_even_divide。",
        "// ⚠️ 冻结表里没有 adc2_n_bits 列：本文件**逐行**换 n_bits（1..20），没有它整份",
        "//    向量无法判读（P_ADC2_BITS 是 elaboration 期参数，不是运行时端口）。故加此列，",
        "//    列序为“紧跟 adc2_code”，其余 6 列顺序不变；该偏离登记在 p2_report.json。",
        "// ⚠️ 前 8 行是 ties-to-even 样例：adc2_n_bits = 1（除数 2 无法用 0 位端口表达）",
        "//    且 delta = adc2_max_q - adc2_min_q = 2x 为**负**（min_q > max_q）。",
        "//    这**刻意违反**载入期不变量 adc2_min_q < adc2_max_q —— 因为这是在单元测试",
        "//    舍入函数本身，不是生产配置。TB 必须绕过 calib_regs 的合法性校验直接驱动。",
        "//    负 delta 的用例数见 p2_report.json 的 scalar_min_gt_max_cases。",
        "// exp_ovf = 1 表示 fine_q 装不进 64 bit 有符号寄存器。",
        "#DATA",
    ]
    min_gt_max = 0
    ties: dict[int, int] = {}
    groups: dict[int, list[int]] = {}
    for index, (code, mn, mx, offset, n_bits) in enumerate(cases):
        if mn > mx:
            min_gt_max += 1
        fine = mn + round_even_divide((2 * code + 1) * (mx - mn), 2 ** (n_bits + 1))
        ovf = int(not -(2**63) <= fine < 2**63)
        if n_bits == 1 and code == 0 and mn == 1000:
            ties[(mx - mn) // 2] = fine - 1000
        groups.setdefault(n_bits, []).append(index)
        lines.append(
            f"{_hex(code, 3)} {_hex(n_bits, 2)} {_shex(mn, 16)} {_shex(mx, 16)} "
            f"{_shex(offset, 16)} {_shex(fine, 16)} {ovf}"
        )
    expected_ties = {-7: -4, -5: -2, -3: -2, -1: 0, 1: 0, 3: 2, 5: 2, 7: 4}
    if ties != expected_ties:
        raise AssertionError(f"ties-to-even samples drifted: {ties} != {expected_ties}")
    text = "\n".join(lines) + "\n"
    _p2_require_marker(text, "p2_scalar.hex")
    _p2_check_size("p2_scalar.hex", text)
    stats = {
        "cases": len(cases),
        "ties_to_even_samples": 8,
        "ties_to_even_result": {str(k): v for k, v in sorted(ties.items())},
        "scalar_min_gt_max_cases": min_gt_max,
        "scalar_min_gt_max_tie_cases": 4,
        "scalar_min_gt_max_note": (
            "冻结要求只登记 4（ties 组里恰好 4 个负 delta）；本文件为覆盖有符号路径"
            "还额外放了负 delta 的系统性用例，故总数更大。"
        ),
        "exp_ovf_set": int(sum(1 for ln in lines[14:] if ln.endswith(" 1"))),
        "adc2_n_bits_used": sorted(groups),
        "extra_column": "adc2_n_bits(2) inserted after adc2_code (frozen table omitted it)",
    }
    return text, stats


# ----------------------------------------------------------------------
# L0 div_floor：定向用例（穷举改成 TB 侧的定义式自检）
# ----------------------------------------------------------------------
def _p2_div_cases() -> list[tuple[int, int]]:
    """Return ``(a, d)`` directed cases for the signed floor divider."""
    divisors = (1, 2, 3, 2**13, 2**30, 2**60 - 1)
    cases = [(a, d) for d in divisors for a in (0, 1, -1, 2, -2)]
    for d in divisors:
        cases += [(d - 1, d), (1 - d, d), (d + 1, d), (-(d + 1), d)]
    big = 2**62 - 1
    cases += [(big, d) for d in divisors]
    cases += [(-big, d) for d in divisors]
    cases += [
        (0, 1),
        (big, 1),
        (-big, 1),
        (big, 2**60 - 1),
        (-big, 2**60 - 1),
        (2**31, 2**31),
        (-(2**31), 2**31),
        (2**61 + 1, 3),
        (-(2**61 + 1), 3),
    ]
    return sorted(set(cases))


def build_p2_div() -> tuple[str, dict[str, Any]]:
    """Export the directed ``div_floor`` golden plus its structural bound checks."""
    cases = _p2_div_cases()
    lines = [
        "// p2_div.hex  (generated by tools/export_rtl_vectors.py)",
        "// cols: a(16 signed) d(16) exp_q(16 signed)",
        "// exp_q = a // d —— Python 的 floor 除法，也就是 fixed_point.py 里 `shifted // denom`",
        "// 用的同一个算子（不是第二份实现）。**定向**用例只有几十条：",
        "// 真正的判据在 TB 侧的定义式自检——对每个 (a, d) 断言 q*d <= a < (q+1)*d（d > 0），",
        "// 用 >=128 bit 宽位算，独立于本模型，也不依赖本文件的期望值。",
        "// 约束：|a| < 2**62（P_W_A = 63 有符号）、0 < d < 2**60（P_W_D = 60 无符号）。",
        "#DATA",
    ]
    for a, d in cases:
        if not (0 < d < 2**60) or not (-(2**62) <= a < 2**62):
            raise AssertionError(f"div case ({a}, {d}) is outside the declared port widths")
        q = a // d
        if not -(2**62) <= q < 2**62:
            raise AssertionError(f"quotient {q} does not fit P_W_A")
        lines.append(f"{_shex(a, 16)} {_hex(d, 16)} {_shex(q, 16)}")
    text = "\n".join(lines) + "\n"
    _p2_require_marker(text, "p2_div.hex")
    _p2_check_size("p2_div.hex", text)
    stats = {
        "cases": len(cases),
        "negative_a": int(sum(1 for a, _ in cases if a < 0)),
        "zero_a": int(sum(1 for a, _ in cases if a == 0)),
        "d_is_one": int(sum(1 for _, d in cases if d == 1)),
        "divisors": [int(d) for d in sorted({d for _, d in cases})],
        "independent_judgement": "TB compares q*d <= a < (q+1)*d in >=128-bit arithmetic",
    }
    return text, stats


