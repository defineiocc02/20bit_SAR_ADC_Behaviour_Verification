# L2 oracle：2**20 全码恒等（矩阵不落文件，只落常量与位宽实测）
# ----------------------------------------------------------------------
def build_p2_oracle() -> tuple[dict[str, str], dict[str, Any]]:
    """Export the oracle's three Q30 weights and its configuration constants."""

    def _factory():
        model = _p2_oracle_model()
        count = 2**model.format.output_bits
        data = _p2_observation(model.spec, np.arange(count, dtype=np.int64))
        stream = model.reconstruct(data)
        if not np.array_equal(stream.code, np.arange(count)):
            raise AssertionError("oracle construction no longer yields dout == adc2_code")
        peaks, observed = _p2_operand_peaks(model, data)
        if observed != stream.peak_accumulator_bits:
            raise AssertionError("operand measurement disagrees with the model's peak ledger")
        return model, stream, peaks, observed

    model, stream, peaks, observed = _memo("oracle", _factory)
    weights = [int(v) for v in model.weights_q.reshape(-1)]
    if len(weights) != 3 or sum(weights) != 2**30 or min(weights) <= 0:
        raise AssertionError("oracle weights must be three positive Q30 values summing to 2**30")
    count = 2**model.format.output_bits
    spec_text = "\n".join(
        [
            "// p2_oracle_spec.hex  (generated by tools/export_rtl_vectors.py)",
            "// cols: w0(12) w1(12) w2(12)   -- oracle 的 3 个 Q30 单位权重",
            "// Q30 source: FixedPointReconstructor.from_weights(spec, [[0.5, 0.25, 0.25]]),",
            f"// sum(w) = {sum(weights)} = 2**30.  三行内容相同：第 0 行是规范行，",
            "// 因此无论 TB 按“一行三个字段”还是“三行各读一次”取值，得到的都是同一组权重。",
            "// mask 全 0 -> plus = 0 -> s = +1 全部单位 -> rails = total = 2**30，I = 0。",
            "#DATA",
        ]
    )
    row = f"{_hex(weights[0], 12)} {_hex(weights[1], 12)} {_hex(weights[2], 12)}"
    spec_text += "\n" + "\n".join([row] * 3) + "\n"
    cfg_text = (
        "\n".join(
            [
                "// p2_oracle_cfg.hex  (generated by tools/export_rtl_vectors.py)",
                "// cols: adc2_min_q(16) adc2_max_q(16) offset_q(16) adc2_n_bits(2)",
                "//       out_count(6) expected_identity(1)",
                "// adc2_max_q = 2**33 是**实测**出来的、唯一让 dout == adc2_code 的取值：",
                "// delta = 2**33 与 adc2_n_bits = 20 给出 F = (2c+1)*2**12，",
                "// 于是 word = floor(F*2**62 / (2**30*2**33)) = floor((2c+1)/2) = c。",
                "// docs/rtl/P2_INTERFACE.md §12 写的 2**25 会让 word 恒为 0（已实测，见报告）。",
                "#DATA",
                f"{_hex(model.adc2_min_q & (2**64 - 1), 16)} "
                f"{_hex(model.adc2_max_q, 16)} {_hex(model.offset_q, 16)} "
                f"{_hex(model.spec.adc2_n_bits, 2)} {_hex(count, 6)} 1",
            ]
        )
        + "\n"
    )
    for name, text in (("p2_oracle_spec.hex", spec_text), ("p2_oracle_cfg.hex", cfg_text)):
        _p2_require_marker(text, name)
        _p2_check_size(name, text)
    stats = {
        "oracle_words": int(count),
        "weights_q": weights,
        "weights_sum": int(sum(weights)),
        "adc2_min_q": int(model.adc2_min_q),
        "adc2_max_q": int(model.adc2_max_q),
        "adc2_n_bits": int(model.spec.adc2_n_bits),
        "out_count": int(count),
        "identity_verified": True,
        "operand_peaks": peaks,
        "model_peak_accumulator_bits": int(observed),
        "peak_accumulator_bits": int(stream.peak_accumulator_bits),
    }
    return {"p2_oracle_spec.hex": spec_text, "p2_oracle_cfg.hex": cfg_text}, stats


