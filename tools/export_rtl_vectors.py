def build_p2_alloc(cfg: Config) -> tuple[str, dict[str, Any]]:
    """Export the 64-cycle A/B ping-pong allocation table straight from the model."""
    from adi_model.pipeline import run_pipeline
    from adi_model.sampler import sine_input

    plan = build_slice_plan(
        cfg,
        P2_ALLOC_SAMPLES,
        np.random.default_rng(cfg.seed + 4201),
        "pingpong",
        spare_period=None,
    )
    result = run_pipeline(
        cfg,
        sine_input(P2_AMPLITUDE_FRAC * cfg.v_fs, cfg.fs * P2_TONE_NUM / P2_TONE_DEN),
        P2_ALLOC_SAMPLES,
    )
    if result.conv_slice_ids is None or result.acq_slice_ids is None:
        raise AssertionError("the pipeline must expose both slice allocations")
    np.testing.assert_array_equal(np.asarray(result.acq_slice_ids)[:P2_ALLOC_SAMPLES], plan.acq)
    np.testing.assert_array_equal(np.asarray(result.conv_slice_ids)[:P2_ALLOC_SAMPLES], plan.conv)
    lines = [
        "// p2_alloc.hex  (generated by tools/export_rtl_vectors.py)",
        "// cols: n(2) acq0..acq7(2 each) conv0..conv7(2 each) bank(1) conv_valid(1)",
        "// 来源：timing.build_slice_plan(strategy='pingpong', spare_period=None)，",
        "//       且与 run_pipeline 的 acq_slice_ids / conv_slice_ids 逐元素核对通过。",
        "// bank 列取自 run_pipeline 实测的 result.bank（见报告 bank_equals_index_mod_2）。",
        "// conv_valid = (n >= 1)：第 0 拍还没有可转换的所有权。",
        "#DATA",
    ]
    bank = np.asarray(result.bank)[:P2_ALLOC_SAMPLES]
    for n in range(P2_ALLOC_SAMPLES):
        fields = [_hex(int(v), 2) for v in plan.acq[n]]
        fields += [_hex(int(v), 2) for v in plan.conv[n]]
        lines.append(f"{_hex(n, 2)} {' '.join(fields)} {int(bank[n]) & 1} {int(plan.valid[n])}")
    text = "\n".join(lines) + "\n"
    _p2_require_marker(text, "p2_alloc.hex")
    _p2_check_size("p2_alloc.hex", text)
    inv4a = bool(np.array_equal(plan.conv[1:], plan.acq[:-1]))
    stats = {
        "cycles": P2_ALLOC_SAMPLES,
        "inv_4a_conv_equals_previous_acq": inv4a,
        "acq_has_no_duplicates": bool(
            all(np.unique(plan.acq[n]).size == cfg.n_active for n in range(P2_ALLOC_SAMPLES))
        ),
        "max_slice_index": int(max(plan.acq.max(), plan.conv.max())),
        "bank_equals_index_mod_2": bool(np.all(bank == np.arange(P2_ALLOC_SAMPLES) % 2)),
    }
    if not inv4a:
        raise AssertionError("INV-4a (conv[n] == acq[n-1]) does not hold in the model")
    return text, stats


