def build(cfg_name: str) -> dict[str, Any]:
    """Produce every P1/P2 vector file in memory.

    Args:
        cfg_name: Key of the config factories; only ``paper_literal`` is supported
            (see the module docstring's applicable domain).

    Returns:
        ``{"files": {name: text}, "report": p1_report, "p2_report": p2_report}``.
    """
    if cfg_name != "paper_literal":
        raise ValueError(
            "P1 vectors are frozen for paper_literal only (H_ROT*W_ROT == 64 is a "
            "precondition of the M2 closed form); re-verify before adding topologies"
        )
    cfg = Config.paper_literal()
    cfg.check_legal()
    # ⚠️ 必须显式打开 dem_enable：工厂默认是 False，而 split_switch_command 在
    # dem_enable=False 时把 states 强制为 0，全部置换退化为恒等 —— 那样生成的
    # 向量会"全绿"却什么都没覆盖（子代理 B 独立复核时发现的陷阱）。
    if cfg.dem_enable:
        raise AssertionError("expected the stock config to be DEM-off; re-check the trap note")
    dem_cfg = replace(cfg, dem_enable=True)

    m1_text, m1_stats = build_m1(dem_cfg)
    m2_text, m2_stats, _ = build_m2(dem_cfg)
    m3_text, m3_stats = build_m3(cfg)
    m5_text, m5_stats = build_m5(dem_cfg)  # bridge off inside; see build_m5
    chain_text, chain_stats = build_chain(cfg)

    files = {
        "p1_m1_sid.hex": m1_text,
        "p1_m2_jinv.hex": m2_text,
        "p1_m3.hex": m3_text,
        "p1_m5_masks.hex": m5_text,
        "p1_chain.hex": chain_text,
    }
    p2_files, p2_report = build_p2(cfg)
    files.update(p2_files)
    report = {
        "schema_version": 1,
        "generator": "tools/export_rtl_vectors.py",
        "config": cfg_name,
        "m1": m1_stats,
        "m2": m2_stats,
        "m3": m3_stats,
        "m5": m5_stats,
        "chain": chain_stats,
        "effective_overrides": {"dem_enable": True},
        "header_default_note": (
            "rtl_params.vh 的 DEM_ENABLE 是**复位默认值**，取自 Config.paper_literal() 的"
            " dem_enable = False；P1 向量则按 dem_enable = True 生成（DEM 关闭时全部置换退化为"
            " 恒等，覆盖不到任何东西）。两者含义不同、不是矛盾，但集成时**必须**让寄存器把"
            " dem_en 打开，否则 RTL 会安静地退化成固定顺序。"
        ),
        "note": "M4 has no golden vector: PCG64 is not reproducible in RTL (interface doc §0.1).",
    }
    return {"files": files, "report": report, "p2_report": p2_report}


def main(argv: list[str] | None = None) -> int:
    """Run the P1/P2 vector exporter.

    Args:
        argv: Command-line arguments; ``None`` means ``sys.argv[1:]``.

    Returns:
        Process exit code: 0 on success, 1 when ``--check`` reports drift.
    """
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", default="paper_literal")
    ap.add_argument("--out-vectors", default="sim/vectors")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)

    root = pathlib.Path(__file__).resolve().parents[1]
    built = build(args.config)
    out_dir = root / args.out_vectors

    drift: list[str] = []
    for name, text in built["files"].items():
        _write(out_dir / name, text, check=args.check, drift=drift)
    _write(
        out_dir / "p1_vectors_report.json",
        _json_text(built["report"]),
        check=args.check,
        drift=drift,
    )
    _write(
        out_dir / "p2_report.json",
        _json_text(built["p2_report"]),
        check=args.check,
        drift=drift,
    )

    if not args.quiet:
        print(f"[export_rtl_vectors] config={args.config}")
        for name, text in built["files"].items():
            state = (
                "DRIFT"
                if str(out_dir / name) in drift
                else ("checked" if args.check else "written")
            )
            print(
                f"  [{state}] {name}  ({len(text.splitlines())} lines, {len(text) / 1024:.0f} KiB)"
            )
        for key in ("m1", "m2", "m3", "m5"):
            print(f"  {key}: {json.dumps(built['report'][key], ensure_ascii=False)}")
        print(
            "  p2: rows="
            + json.dumps(built["p2_report"]["file_rows"], ensure_ascii=False)
            + f"  largest={built['p2_report']['largest_file_bytes']} B"
        )
        print(f"  p2 peak_bits: {json.dumps(built['p2_report']['peak_bits'], ensure_ascii=False)}")
    if drift:
        print(f"[export_rtl_vectors] DRIFT: {len(drift)} artifact(s) differ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
